let lang = "fr";
try {
  lang = localStorage.getItem("iak.lang") ||
         ((navigator.language || "fr").toLowerCase().startsWith("fr") ? "fr" : "en");
} catch (_) { /* storage unavailable */ }

export function getLang() { return lang; }

export function setLang(value) {
  lang = TEXTS[value] ? value : "fr";
  try { localStorage.setItem("iak.lang", lang); } catch (_) { /* ignore */ }
  document.documentElement.lang = lang;
}

export function t(key, vars = {}) {
  const s = (TEXTS[lang] && TEXTS[lang][key]) ?? TEXTS.en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (k in vars ? String(vars[k]) : `{${k}}`));
}

/** Fill every [data-i18n] element (text) and [data-i18n-placeholder]. */
export function translatePage(root = document) {
  root.querySelectorAll("[data-i18n]").forEach((el) => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  });
  root.querySelectorAll("[data-i18n-title]").forEach((el) => { el.title = t(el.dataset.i18nTitle); });
}
